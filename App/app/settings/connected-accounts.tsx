import { useCallback, useEffect, useState } from 'react';
import { KeyboardAvoidingView, Platform, ScrollView, StyleSheet, Text, TextInput, View } from 'react-native';
import { useRouter } from 'expo-router';
import { useSafeAreaInsets } from 'react-native-safe-area-context';
import { isSupabaseConfigured } from '../../src/lib/supabase';
import { fetchConnectedAccounts, verifyLinkCode, VerifyCodeResult } from '../../src/api/accounts';
import { KIBButton } from '../../src/components/KIBPrimitives';
import { colors, radius, spacing, type } from '../../src/theme';

/**
 * SCREEN — CONNECTED ACCOUNTS. Documents how the Instagram DM code link
 * works. The code is generated by KeepItBack's Instagram professional
 * account (real Meta Messaging integration), never displayed here. Code
 * verification runs server-side via the `link-code` Edge Function; a
 * missing deployment or secret surfaces as "Not configured", not a fake
 * success. This does NOT import your existing Instagram Saved collection.
 */
export default function ConnectedAccounts() {
  const router = useRouter();
  const insets = useSafeAreaInsets();
  const [accounts, setAccounts] = useState<{ id: string; provider_username?: string | null; linked_at: string }[]>([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [state, setState] = useState<VerifyCodeResult | null>(null);

  const reload = useCallback(async () => {
    const res = await fetchConnectedAccounts();
    setLoading(false);
    if (res.error) setLoadError(res.error);
    else setAccounts(res.data ?? []);
  }, []);

  useEffect(() => {
    void (async () => {
      const res = await fetchConnectedAccounts();
      setLoading(false);
      if (res.error) setLoadError(res.error);
      else setAccounts(res.data ?? []);
    })();
  }, []);

  const submitCode = async () => {
    if (!code.trim() || busy) return;
    setBusy(true);
    setState(null);
    const res = await verifyLinkCode(code);
    setBusy(false);
    setState(res);
    if ('ok' in res && res.ok) {
      setCode('');
      void reload();
    }
  };

  const stateNotConfigured = !!state && 'notConfigured' in state && (state as { notConfigured: true }).notConfigured;
  const notConfigured = !isSupabaseConfigured || stateNotConfigured;

  return (
    <KeyboardAvoidingView behavior={Platform.OS === 'ios' ? 'padding' : undefined} style={styles.container}>
      <ScrollView contentContainerStyle={{ paddingTop: insets.top + spacing.xl, paddingBottom: 60, paddingHorizontal: spacing.xl, gap: spacing.md }}>
        <Text style={[type.h3 as any, { color: colors.text }]}>Connected accounts</Text>
        <Text style={{ color: colors.textSecondary, fontSize: 14 }}>
          KeepItBack links content sent to its official Instagram account by matching a one-time code. Save a Reel or post by DM-ing it to
          KeepItBack after linking — nothing from your existing Instagram Saved collection is imported.
        </Text>

        {/* Real linked rows from Supabase */}
        <View style={{ marginTop: spacing.md, gap: 6 }}>
          <Text style={{ color: colors.textMuted, fontSize: 13 }}>Linked Instagram senders</Text>
          {notConfigured ? (
            <View style={[styles.warnBox, { borderColor: colors.error }]}>
              <Text style={{ color: colors.error, fontSize: 13 }}>Not configured</Text>
              <Text style={{ color: colors.textMuted, fontSize: 12, marginTop: 4 }}>
                The link-code server function or Meta app secrets aren&apos;t set up yet. See README §Instagram connection — code entry can&apos;t verify anything until then, and this screen won&apos;t pretend otherwise.
              </Text>
            </View>
          ) : loading ? (
            <Text style={{ color: colors.textMuted, fontSize: 13 }}>Checking…</Text>
          ) : loadError ? (
            <Text style={{ color: colors.error, fontSize: 13 }}>{loadError}</Text>
          ) : accounts.length === 0 ? (
            <Text style={{ color: colors.textMuted, fontSize: 13 }}>Nothing linked yet.</Text>
          ) : (
            accounts.map((a) => (
              <View key={a.id} style={styles.statusRow}>
                <Text style={{ color: colors.text, fontSize: 14 }}>Instagram sender · {a.provider_username ?? 'sender id on file'}</Text>
                <Text style={{ color: colors.success, fontSize: 13 }}>Linked {new Date(a.linked_at).toLocaleDateString()}</Text>
              </View>
            ))
          )}
        </View>

        {/* Code entry */}
        <View style={{ marginTop: spacing.lg, gap: 8 }}>
          <Text style={{ color: colors.text, fontSize: 15 }}>Enter verification code</Text>
          <Text style={{ color: colors.textMuted, fontSize: 13 }}>
            Message the official KeepItBack Instagram account with anything (e.g. &quot;hi&quot;). It replies with a one-time code, valid 10 minutes; enter it here while signed in.
          </Text>
          <TextInput
            value={code}
            onChangeText={(t) => {
              setCode(t.toUpperCase());
              setState(null);
            }}
            placeholder="ABC-1234"
            placeholderTextColor={colors.textMuted}
            autoCapitalize="characters"
            accessibilityLabel="Verification code"
            style={styles.input}
          />
          <KIBButton label={busy ? 'Verifying…' : 'Link account'} onPress={submitCode} disabled={busy || !code.trim()} />
          {state && 'error' in state ? <Text style={{ color: colors.error, fontSize: 13 }}>{state.error}</Text> : null}
          {state && 'ok' in state && state.ok ? (
            <Text style={{ color: colors.success, fontSize: 13 }}>Linked! Content you DM to KeepItBack&apos;s Instagram will be saved to your library.</Text>
          ) : null}
        </View>

        <KIBButton label="Done" variant="ghost" onPress={() => router.back()} style={{ marginTop: spacing.md }} />
      </ScrollView>
    </KeyboardAvoidingView>
  );
}

const styles = StyleSheet.create({
  container: { flex: 1, backgroundColor: colors.bg },
  input: {
    height: 52,
    backgroundColor: colors.surface,
    borderColor: colors.border,
    borderWidth: 1,
    borderRadius: radius.md,
    color: colors.text,
    paddingHorizontal: spacing.lg,
    fontSize: 17,
    letterSpacing: 2,
  },
  statusRow: {
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'space-between',
    backgroundColor: colors.surface,
    borderColor: colors.border,
    borderWidth: 1,
    borderRadius: radius.sm,
    padding: spacing.md,
  },
  warnBox: { borderWidth: 1, borderRadius: radius.md, padding: spacing.md, backgroundColor: colors.surface },
});
